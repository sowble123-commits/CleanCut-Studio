from PIL import Image, ImageDraw

# ==========================================
# 샘플 1: 단색 배경 + 회색 노이즈 테두리 + 넓은 여백 (600x350)
# ==========================================
img1 = Image.new("RGB", (600, 350), (255, 255, 255))  # 순백색 넓은 배경
draw1 = ImageDraw.Draw(img1)

# 바깥쪽 애매한 밝은 회색 그림자 영역 (강도 '약하게'에서는 남고, '표준/강하게'에서는 지워짐!)
draw1.ellipse((190, 65, 410, 285), fill=(225, 225, 225))

# 메인 파란색 원형 로고 (절대 지워지면 안 되는 피사체)
draw1.ellipse((215, 90, 385, 260), fill=(59, 130, 246), outline=(29, 78, 216), width=6)

# 안쪽의 흰색 눈동자 (모서리와 연결되지 않은 내부 흰색이 안전하게 보호되는지 확인용)
draw1.ellipse((255, 140, 285, 175), fill=(255, 255, 255))
draw1.ellipse((315, 140, 345, 175), fill=(255, 255, 255))
draw1.ellipse((265, 150, 278, 165), fill=(15, 23, 42))
draw1.ellipse((325, 150, 338, 165), fill=(15, 23, 42))
draw1.arc((260, 175, 340, 225), start=10, end=170, fill=(255, 255, 255), width=6)

img1.save("샘플1_단색배경_강도테스트.png")


# ==========================================
# 샘플 2: 복잡한 컬러 배경 + 피사체 + 워터마크 글씨 (500x500)
# ==========================================
img2 = Image.new("RGB", (500, 500))
px = img2.load()

# 단색 제거로는 절대 못 지우는 알록달록한 그라데이션 + 격자 배경 생성
for y in range(500):
    for x in range(500):
        r = int(40 + (x / 500) * 120)
        g = int(140 - (y / 500) * 80)
        b = int(100 + ((x + y) / 1000) * 120)
        if (x // 40 + y // 40) % 2 == 0:
            r, g, b = min(255, r + 25), min(255, g + 25), min(255, b + 25)
        px[x, y] = (r, g, b)

draw2 = ImageDraw.Draw(img2)

# 중앙에 선명한 주황색 고양이/로봇 피사체 그리기
draw2.polygon([(160, 180), (190, 90), (240, 150)], fill=(234, 88, 12))   # 왼쪽 귀
draw2.polygon([(340, 180), (310, 90), (260, 150)], fill=(234, 88, 12))   # 오른쪽 귀
draw2.rounded_rectangle((150, 140, 350, 380), radius=50, fill=(249, 115, 22), outline=(154, 52, 18), width=6)
draw2.ellipse((195, 200, 230, 235), fill=(254, 240, 138))               # 왼쪽 눈
draw2.ellipse((270, 200, 305, 235), fill=(254, 240, 138))               # 오른쪽 눈
draw2.ellipse((207, 210, 220, 225), fill=(0, 0, 0))
draw2.ellipse((282, 210, 295, 225), fill=(0, 0, 0))
draw2.polygon([(240, 250), (260, 250), (250, 268)], fill=(254, 202, 202)) # 코

# 몸통 한가운데에 지저분한 워터마크 박스 및 텍스트 박기 (2번 탭 매직 지우개 테스트용)
draw2.rectangle((175, 305, 325, 345), fill=(255, 255, 255))
draw2.text((192, 318), "WATERMARK 2026", fill=(220, 38, 38))

img2.save("샘플2_복잡한배경_AI누끼_지우개테스트.jpg", quality=95)

print("✅ 테스트용 샘플 이미지 2장 생성 완료!")